    private void signupBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signupBtnActionPerformed

        String uN = username.getText().trim();
        String email_address = email_Address.getText().trim();
        String student_id = studentID.getText().trim();
        String yearLevel = yearLvl.getSelectedItem() == null
        ? ""
        : yearLvl.getSelectedItem().toString().trim();
        String contactNumber = contact.getText().trim();

        String password = new String(txtPassword.getPassword());
        String confirmPassword =
                new String(txtConfirmPassword.getPassword());

        // Validate Student ID
        if (student_id.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Student ID is required!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            studentID.requestFocus();
            return;
        }

        // Validate username
        if (uN.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Username is required!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            username.requestFocus();
            return;
        }

        // Validate email
        if (email_address.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Email is required!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            email_Address.requestFocus();
            return;
        }

        // Basic email format validation
        if (!email_address.matches("^[A-Za-z0-9+_.-]+@[A-Za-z0-9.-]+$")) {
            JOptionPane.showMessageDialog(
                    this, "Please enter a valid email address!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            email_Address.requestFocus();
            return;
        }

        // Validate year level
        if (yearLevel.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Year level is required!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            yearLvl.requestFocus();
            return;
        }

        // Validate password
        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Password is required!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            txtPassword.requestFocus();
            return;
        }

        // Validate contact number
        if (contactNumber.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Contact number is required!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            email_Address.requestFocus();
            return;
        }

        // Validate confirm password
        if (confirmPassword.isEmpty()) {
            JOptionPane.showMessageDialog(
                    this, "Please confirm your password!",
                    "Sign Up", JOptionPane.ERROR_MESSAGE);
            txtConfirmPassword.requestFocus();
            return;
        }

        // Check password confirmation
        if (!password.equals(confirmPassword)) {
            JOptionPane.showMessageDialog(
                    this,
                    "Password and Confirm Password do not match!",
                    "Password Error",
                    JOptionPane.ERROR_MESSAGE);

            txtConfirmPassword.setText("");
            txtConfirmPassword.requestFocus();
            return;
        }

        try {
            // Prepare JSON payload for POST /api/users
            org.json.JSONObject payload =
                    new org.json.JSONObject();

            payload.put("name", uN);
            payload.put("email", email_address);
            payload.put("student_id", student_id);
            payload.put("year_level", yearLevel);
            payload.put("contact_no", contactNumber);

            // Include these only if your Laravel API accepts them
            payload.put("password", password);
            payload.put("role", "user");

            // Call Laravel API
            String response =
                    lostandfoundapp.apis.apis.createUser(payload);

            JOptionPane.showMessageDialog(
                    this,
                    "Account created successfully!",
                    "Sign Up",
                    JOptionPane.INFORMATION_MESSAGE);

            // Clear fields after successful signup
            username.setText("");
            studentID.setText("");
            yearLvl.setSelectedIndex(-1);
            email_Address.setText("");
            txtPassword.setText("");
            txtConfirmPassword.setText("");
            contact.setText("");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(
                    this,
                    "Error during sign up:\n" + e.getMessage(),
                    "Sign Up Error",
                    JOptionPane.ERROR_MESSAGE);
        }
    

    }//GEN-LAST:event_signupBtnActionPerformed

